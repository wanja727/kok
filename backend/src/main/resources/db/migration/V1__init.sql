-- 1주차 스키마: 사용자, 콘텐츠, 풀이, 지연 확인
-- XP 원장·스트릭·랭킹은 2주차 이후 마이그레이션으로 추가한다

-- 사용자. 비밀번호 열은 두지 않는다 (OAuth만 쓴다)
create table users (
    id            bigint generated by default as identity primary key,
    nickname      varchar(50) not null,
    daily_goal_xp int         not null default 30,
    created_at    timestamptz not null default now()
);

-- 로그인 수단. 한 사용자에게 카카오·GitHub·Google을 여러 개 연결할 수 있다
create table user_identity (
    id               bigint generated by default as identity primary key,
    user_id          bigint       not null references users (id),
    provider         varchar(20)  not null,
    provider_user_id varchar(100) not null,
    created_at       timestamptz  not null default now(),
    unique (provider, provider_user_id)
);

-- 콘텐츠: 주제 > 단원 > 레슨 > 개념 > 문제
-- external_key는 콘텐츠 파일의 키다. 가져오기를 다시 돌려도 같은 행을 찾는다
create table subject (
    id   bigint generated by default as identity primary key,
    slug varchar(50)  not null unique,
    name varchar(100) not null
);

create table unit (
    id         bigint generated by default as identity primary key,
    subject_id bigint       not null references subject (id),
    title      varchar(100) not null,
    sort_order int          not null default 0,
    unique (subject_id, title)
);

create table lesson (
    id           bigint generated by default as identity primary key,
    unit_id      bigint       not null references unit (id),
    external_key varchar(200) not null unique,
    title        varchar(200) not null,
    sort_order   int          not null default 0
);

create table concept (
    id           bigint generated by default as identity primary key,
    lesson_id    bigint       not null references lesson (id),
    external_key varchar(200) not null unique,
    name         varchar(200) not null
);

-- 문제. 내용은 question_version에 두고, 고칠 때마다 새 버전을 만든다
-- purpose: PRACTICE(연습, 자기 채점) / JUDGMENT(판정, 자동 채점. 지연 확인은 판정 문제로만)
create table question (
    id                 bigint generated by default as identity primary key,
    external_key       varchar(200) not null unique,
    lesson_id          bigint       not null references lesson (id),
    concept_id         bigint       not null references concept (id),
    purpose            varchar(20)  not null,
    status             varchar(20)  not null,
    sort_order         int          not null default 0,
    current_version_id bigint
);

create table question_version (
    id           bigint generated by default as identity primary key,
    question_id  bigint      not null references question (id),
    version_no   int         not null,
    type         varchar(20) not null,
    body         text        not null,
    code         text,
    choices      jsonb,
    answer       varchar(50),
    explanation  text        not null,
    checklist    jsonb,
    source_url   varchar(500),
    difficulty   int         not null,
    content_hash varchar(64) not null,
    created_at   timestamptz not null default now(),
    unique (question_id, version_no)
);

alter table question
    add constraint fk_question_current_version
        foreign key (current_version_id) references question_version (id);

create index idx_question_lesson on question (lesson_id, sort_order);
create index idx_question_concept on question (concept_id);

-- 답안 제출. 풀 당시의 문제 버전을 가리킨다
-- (user_id, client_submission_id) 유니크로 재시도·두 번 누르기를 막는다
create table answer_submission (
    id                   bigint generated by default as identity primary key,
    user_id              bigint      not null references users (id),
    question_version_id  bigint      not null references question_version (id),
    client_submission_id uuid        not null,
    selected             varchar(50) not null,
    confidence           varchar(10) not null,
    correct              boolean     not null,
    is_delayed_check     boolean     not null default false,
    service_date         date        not null,
    submitted_at         timestamptz not null,
    unique (user_id, client_submission_id)
);

create index idx_submission_user_version on answer_submission (user_id, question_version_id);

-- 지연 확인: 개념을 처음 푼 날 기준 3일(attempt 1), 7일(attempt 2) 뒤
create table delayed_check (
    user_id             bigint      not null references users (id),
    concept_id          bigint      not null references concept (id),
    attempt_no          int         not null,
    due_date            date        not null,
    result              varchar(10),
    checked_at          timestamptz,
    question_version_id bigint references question_version (id),
    primary key (user_id, concept_id, attempt_no)
);

-- 오늘 확인할 개념 조회용. 아직 확인하지 않은 행만 담는다
create index idx_delayed_check_due on delayed_check (user_id, due_date) where result is null;
