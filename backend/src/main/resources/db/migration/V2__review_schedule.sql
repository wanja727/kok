-- 복습 기준 (ADR-017): 배운 날 3번 정답, 그 뒤 3일·7일·21일 재확인, 네 번 통과하면 졸업
-- 1주차는 처음 푼 날 3일·7일 확인 행을 미리 만들었다. 이제 개념마다 진행 상태 한 행을 두고, 확인할 때마다 다음 날짜를 정한다

-- 사용자별 개념 진행 상태
-- stage: 통과한 확인 수. 0 = 배우는 중(배운 날 3번 정답 전), 1~3 = 재확인 중, 4 = 졸업
-- due_date: 다음 확인 날. 배우는 중이거나 졸업했으면 null
-- sure_wrong: 마지막 확인에서 확실했는데 틀림. 다음 날 다른 개념보다 먼저 묻는다
create table concept_progress (
    user_id      bigint      not null references users (id),
    concept_id   bigint      not null references concept (id),
    stage        int         not null check (stage between 0 and 4),
    learned_on   date,
    due_date     date,
    sure_wrong   boolean     not null default false,
    graduated_at timestamptz,
    updated_at   timestamptz not null,
    primary key (user_id, concept_id),
    check ((stage between 1 and 3) = (due_date is not null))
);

-- 오늘 확인할 개념 조회용. 재확인 중인 행만 담는다
create index idx_concept_progress_due on concept_progress (user_id, due_date) where due_date is not null;

-- 1주차 데이터 옮기기 (개발 데이터뿐이다)
-- 아직 확인하지 않은 가장 앞 회차를 다음 확인으로 본다. 두 회차를 다 확인했으면 21일 확인을 마지막 확인 14일 뒤로 잡는다
insert into concept_progress (user_id, concept_id, stage, learned_on, due_date, updated_at)
select user_id,
       concept_id,
       coalesce(min(attempt_no) filter (where result is null), 3),
       min(due_date) filter (where attempt_no = 1) - 3,
       coalesce(min(due_date) filter (where result is null), max(checked_at)::date + 14),
       now()
from delayed_check
group by user_id, concept_id;

delete from delayed_check where result is null;

-- delayed_check는 이제 확인 기록이다. 확인할 때마다 한 행을 남긴다
-- 틀리면 같은 단계를 다시 확인하므로 (사용자, 개념, 회차)가 겹칠 수 있다
drop index idx_delayed_check_due;
alter table delayed_check drop constraint delayed_check_pkey;
alter table delayed_check add column id bigint generated by default as identity primary key;
alter table delayed_check add column stage_after int;
update delayed_check set stage_after = case when result = 'CORRECT' then attempt_no + 1 else greatest(attempt_no - 1, 1) end;
alter table delayed_check alter column result set not null;
alter table delayed_check alter column checked_at set not null;
alter table delayed_check alter column stage_after set not null;

comment on column delayed_check.attempt_no is '확인할 때의 단계(통과한 확인 수). 1 = 3일, 2 = 7일, 3 = 21일 확인';
comment on column delayed_check.stage_after is '확인 뒤의 단계. 4면 졸업';

create index idx_delayed_check_user_concept on delayed_check (user_id, concept_id);
